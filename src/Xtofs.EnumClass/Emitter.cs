using System.Globalization;
using System.Linq;

using Microsoft.CodeAnalysis.CSharp;

namespace Xtofs.EnumClass.Generator
{
    internal static class Emitter
    {
        private const string Sys = "global::System";
        private const string Inline =
            "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]";

        public static string Emit(EmitModel e)
        {
            var m = e.Type;
            int n = e.AllNames.Length;                   // own values + all included blocks
            int own = m.Members.Length;
            string self = m.Name;
            string ord = n <= 256 ? "byte" : "ushort";
            int k = (n + 63) / 64;                       // 64-bit words in a Set
            string[] w = Enumerable.Range(0, k).Select(i => $"_w{i}").ToArray();

            var o = new Writer();
            o.Line("// <auto-generated/>")
             .Line("#nullable enable")
             .Line("#pragma warning disable CS1591")
             .Line();
            if (m.Namespace is not null) o.Line($"namespace {m.Namespace};").Line();
            // The user's usings, so that crefs in copied member doc comments bind as written.
            // Everything generated below is fully qualified and unaffected by them.
            foreach (var u in m.Usings) o.Line(u);
            if (m.Usings.Length > 0) o.Line();

            o.Line($"[{Sys}.Diagnostics.DebuggerDisplay(\"{{ToString(),nq}}\")]");
            o.Open($"readonly partial struct {self} : {Sys}.IEquatable<{self}>, {Sys}.IComparable<{self}>");

            // ---- representation -------------------------------------------------
            o.Line(own == n ? "/// <summary>Number of values.</summary>" : "/// <summary>Number of values, own and included.</summary>")
             .Line($"public const int Count = {n};")
             .Line()
             .Line($"private readonly {ord} _ordinal;")
             .Line($"private {self}({ord} ordinal) => _ordinal = ordinal;")
             .Line()
             .Line(own == n
                 ? "/// <summary>Zero-based index in the Members initializer. Note: <c>default</c> is the first value.</summary>"
                 : "/// <summary>Own values first (Members initializer order), then each included block. Note: <c>default</c> is the first own value.</summary>")
             .Line("public int Ordinal => _ordinal;")
             .Line();

            // ---- members (doc comments copied from the Members initializer) ------
            for (int i = 0; i < own; i++)
            {
                foreach (var doc in m.Members[i].DocLines) o.Line(doc);
                o.Line($"public static {self} {Id(m.Members[i].Name)} => new({i});");
            }
            o.Line();

            EmitDataInput(o, m);

            // ---- tables ---------------------------------------------------------
            EmitIncludes(o, e, self, ord);

            o.Line($"private static readonly string[] s_names = [{Join(e.AllNames.Select(Quote))}];");
            o.Line($"private static readonly {self}[] s_values = [{Join(Enumerable.Range(0, n).Select(i => $"new({i})"))}];");
            o.Line()
             .Line("/// <summary>All values in ordinal order.</summary>")
             .Line($"public static {Sys}.ReadOnlySpan<{self}> Values => s_values;")
             .Line();

            // Ordinal is always in [0, Count) — the only ways to obtain an instance are the
            // private constructor (called with valid ordinals) and default (ordinal 0).
            o.Line(Inline)
             .Line("private T GetAt<T>(T[] table) =>")
             .Line($"    {Sys}.Runtime.CompilerServices.Unsafe.Add(ref {Sys}.Runtime.InteropServices.MemoryMarshal.GetArrayDataReference(table), (int)_ordinal);")
             .Line();

            // ---- associated data ------------------------------------------------
            // Columns are filled from Members once, during type initialization. s_table is
            // declared first: field initializers run in textual order within one part.
            if (m.Properties.Length > 0)
                o.Line($"private static readonly Table s_table = {MembersName};").Line();
            foreach (var p in m.Properties)
            {
                o.Line($"private static readonly {p.Type}[] s_{p.Name} = [{Join(m.Members.Select(x => $"s_table.{Id(x.Name)}.{Id(p.Name)}"))}];");
                o.Line($"{p.Modifiers} {p.Type} {Id(p.Name)} {{ get => GetAt(s_{p.Name}); }}");
                o.Line();
            }

            if (m.GenerateName)
                o.Line("/// <summary>The member identifier.</summary>")
                 .Line("public string Name => GetAt(s_names);");
            o.Line("public override string ToString() => GetAt(s_names);").Line();

            // ---- switchable tag -------------------------------------------------
            o.Line("/// <summary>A plain enum mirroring the members, for <c>switch</c> with constant patterns.</summary>");
            o.Open($"public enum Kind : {ord}");
            for (int i = 0; i < n; i++) o.Line($"{Id(e.AllNames[i])} = {i},");
            o.Close();
            o.Line("public Kind Tag => (Kind)_ordinal;");
            o.Line($"public static {self} FromTag(Kind tag) => FromOrdinal((int)tag);").Line();

            // ---- ordinals -------------------------------------------------------
            o.Line($"public static {self} FromOrdinal(int ordinal) =>")
             .Line($"    (uint)ordinal < (uint)Count ? new(({ord})ordinal) : throw new {Sys}.ArgumentOutOfRangeException(nameof(ordinal));")
             .Line();
            o.Open($"public static bool TryFromOrdinal(int ordinal, out {self} value)")
             .Line($"if ((uint)ordinal < (uint)Count) {{ value = new(({ord})ordinal); return true; }}")
             .Line("value = default;")
             .Line("return false;")
             .Close().Line();

            EmitParsing(o, e, self, ord);
            EmitEquality(o, self, ord);
            EmitSet(o, e, self, ord, n, k, w);

            o.Close();
            return o.ToString();
        }

        private const string MembersName = EnumClassGenerator.MembersPropertyName;

        /// <summary>Row and Table, the input types of the user's Members property.</summary>
        private static void EmitDataInput(Writer o, TypeModel m)
        {
            var props = m.Properties;

            o.Line("/// <summary>One member's data; constructor parameters follow data-property declaration order.</summary>");
            o.Open("private readonly struct Row");
            foreach (var p in props) o.Line($"public readonly {p.Type} {Id(p.Name)};");
            if (props.Length > 0)
            {
                o.Line($"public Row({Join(props.Select(p => $"{p.Type} {Id(p.Name)}"))})");
                o.Line($"{{ {string.Join(" ", props.Select(p => $"this.{Id(p.Name)} = {Id(p.Name)};"))} }}");
            }
            o.Close().Line();

            o.Line($"/// <summary>Input to <see cref=\"{MembersName}\"/>: one property per member, generated from its initializer.</summary>");
            o.Open($"private sealed class {EnumClassGenerator.TableTypeName}");
            foreach (var x in m.Members) o.Line($"public Row {Id(x.Name)} {{ get; init; }}");
            o.Close().Line();

        }

        /// <summary>Widening/narrowing between this type and each included type.</summary>
        private static void EmitIncludes(Writer o, EmitModel e, string self, string ord)
        {
            foreach (var inc in e.Includes)
            {
                string t = inc.FullName, s = inc.SimpleName;
                string range = $"ordinals {inc.Offset}..{inc.Offset + inc.Count - 1}";
                o.Line($"/// <summary>Every <see cref=\"{inc.DisplayName}\"/> value is a <see cref=\"{self}\"/> value ({range}).</summary>")
                 .Line($"public static implicit operator {self}({t} value) => new(({ord})(value.Ordinal + {inc.Offset}));")
                 .Line($"/// <exception cref=\"{Sys}.InvalidCastException\">The value is not a <see cref=\"{inc.DisplayName}\"/>.</exception>")
                 .Line($"public static explicit operator {t}({self} value) =>")
                 .Line($"    value.TryGet{s}(out var v) ? v : throw new {Sys}.InvalidCastException($\"{{value}} is not a {s}.\");")
                 .Line($"/// <summary>Whether this value is a <see cref=\"{inc.DisplayName}\"/> ({range}).</summary>")
                 .Line($"public bool Is{s} => (uint)(_ordinal - {inc.Offset}) < {inc.Count}u;");
                o.Open($"public bool TryGet{s}(out {t} value)")
                 .Line($"int i = _ordinal - {inc.Offset};")
                 .Line($"if ((uint)i < {inc.Count}u) {{ value = {t}.FromOrdinal(i); return true; }}")
                 .Line("value = default;")
                 .Line("return false;")
                 .Close().Line();
            }
        }

        /// <summary>Escapes reserved keywords (<c>@class</c>).</summary>
        private static string Id(string name) =>
            SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

        private static void EmitParsing(Writer o, EmitModel m, string self, string ord)
        {
            bool phf = m.PhfDisplacements.Length > 0;
            string ros = $"{Sys}.ReadOnlySpan<char>";

            if (phf)
            {
                o.Line($"private const bool PhfFold = {(m.PhfFold ? "true" : "false")};");
                // Collection expressions over constants into ReadOnlySpan<T> compile to static PE data.
                o.Line($"private static {Sys}.ReadOnlySpan<int> PhfDisplacements => [{Join(m.PhfDisplacements.Select(Num))}];");
                o.Line($"private static {Sys}.ReadOnlySpan<{ord}> PhfSlots => [{Join(m.PhfSlots.Select(Num))}];");
                o.Line();
            }

            o.Line($"public static bool TryParse({ros} name, out {self} value) => TryParse(name, false, out value);").Line();

            o.Line("/// <summary>Looks up a member by identifier. <paramref name=\"ignoreCase\"/> folds ASCII letters only.</summary>");
            o.Open($"public static bool TryParse({ros} name, bool ignoreCase, out {self} value)");
            if (!phf)
            {
                o.Line("return TryParseLinear(name, ignoreCase, out value);");
            }
            else
            {
                if (!m.PhfFold) o.Line("if (ignoreCase) return TryParseLinear(name, true, out value);");
                o.Line("int ordinal = PhfSlots[global::Xtofs.EnumClass.Internal.PerfectHash.Slot(name, PhfDisplacements, PhfFold)];")
                 .Line("string candidate = s_names[ordinal];")
                 .Line("if (ignoreCase")
                 .Line($"        ? {Sys}.Text.Ascii.EqualsIgnoreCase(name, candidate)")
                 .Line($"        : {Sys}.MemoryExtensions.SequenceEqual(name, {Sys}.MemoryExtensions.AsSpan(candidate)))")
                 .Line("{")
                 .Line($"    value = new(({ord})ordinal);")
                 .Line("    return true;")
                 .Line("}")
                 .Line("value = default;")
                 .Line("return false;");
            }
            o.Close().Line();

            if (!phf || !m.PhfFold)
            {
                o.Open($"private static bool TryParseLinear({ros} name, bool ignoreCase, out {self} value)")
                 .Open("for (int i = 0; i < s_names.Length; i++)")
                 .Line("if (ignoreCase")
                 .Line($"        ? {Sys}.Text.Ascii.EqualsIgnoreCase(name, s_names[i])")
                 .Line($"        : {Sys}.MemoryExtensions.SequenceEqual(name, {Sys}.MemoryExtensions.AsSpan(s_names[i])))")
                 .Line($"{{ value = new(({ord})i); return true; }}")
                 .Close()
                 .Line("value = default;")
                 .Line("return false;")
                 .Close().Line();
            }

            o.Line($"public static bool TryParse(string? name, out {self} value) => TryParse({Sys}.MemoryExtensions.AsSpan(name), false, out value);");
            o.Line($"public static {self} Parse({ros} name, bool ignoreCase = false) =>")
             .Line($"    TryParse(name, ignoreCase, out var v) ? v : throw new {Sys}.FormatException($\"'{{name.ToString()}}' is not a member of {self}.\");")
             .Line();
        }

        private static void EmitEquality(Writer o, string self, string ord)
        {
            o.Line($"public bool Equals({self} other) => _ordinal == other._ordinal;")
             .Line($"public override bool Equals(object? obj) => obj is {self} other && _ordinal == other._ordinal;")
             .Line("public override int GetHashCode() => _ordinal;")
             .Line($"public int CompareTo({self} other) => _ordinal.CompareTo(other._ordinal);")
             .Line($"public static bool operator ==({self} left, {self} right) => left._ordinal == right._ordinal;")
             .Line($"public static bool operator !=({self} left, {self} right) => left._ordinal != right._ordinal;")
             .Line()
             .Line("/// <summary><c>A | B</c> on two members yields a <see cref=\"Set\"/>.</summary>")
             .Line($"public static Set operator |({self} left, {self} right) => Set.Of(left) | Set.Of(right);")
             .Line();
        }

        private static void EmitSet(Writer o, EmitModel m, string self, string ord, int n, int k, string[] w)
        {
            string[] masks = Enumerable.Range(0, k).Select(i =>
            {
                int bits = System.Math.Min(64, n - 64 * i);
                ulong mask = bits == 64 ? ulong.MaxValue : (1UL << bits) - 1;
                return "0x" + mask.ToString("X16", CultureInfo.InvariantCulture) + "UL";
            }).ToArray();

            string Each(System.Func<int, string> f, string sep = ", ") => string.Join(sep, Enumerable.Range(0, k).Select(f));
            string bo = "global::System.Numerics.BitOperations";

            o.Line($"/// <summary>Immutable bit set of <see cref=\"{self}\"/> ({k} × 64-bit word{(k > 1 ? "s" : "")}). Supports collection expressions.</summary>");
            o.Line($"[{Sys}.Runtime.CompilerServices.CollectionBuilder(typeof(Set), nameof(Set.Create))]");
            o.Line($"[{Sys}.Diagnostics.DebuggerDisplay(\"{{ToString(),nq}}\")]");
            o.Open($"public readonly struct Set : {Sys}.IEquatable<Set>");

            o.Line($"private readonly ulong {string.Join(", ", w)};");
            o.Line($"private Set({Each(i => $"ulong w{i}")}) {{ {Each(i => $"{w[i]} = w{i};", " ")} }}").Line();

            o.Line("public static Set Empty => default;");
            o.Line($"public static Set All => new({string.Join(", ", masks)});").Line();

            // Of / Contains — single word is branch-free; multi-word selects by o >> 6.
            // C# masks shift counts for ulong to 6 bits, so 1UL << o == 1UL << (o & 63).
            o.Line(Inline);
            if (k == 1)
                o.Line($"public static Set Of({self} item) => new(1UL << item._ordinal);");
            else
            {
                o.Open($"public static Set Of({self} item)")
                 .Line("int o = item._ordinal, word = o >> 6;")
                 .Line("ulong bit = 1UL << o;")
                 .Line($"return new({Each(i => $"word == {i} ? bit : 0UL")});")
                 .Close();
            }
            o.Line();

            o.Line(Inline);
            if (k == 1)
                o.Line($"public bool Contains({self} item) => ((_w0 >> item._ordinal) & 1UL) != 0;");
            else
            {
                o.Open($"public bool Contains({self} item)")
                 .Line("int o = item._ordinal;")
                 .Line($"ulong word = (o >> 6) switch {{ {string.Join(", ", Enumerable.Range(0, k - 1).Select(i => $"{i} => {w[i]}"))}, _ => {w[k - 1]} }};")
                 .Line("return ((word >> o) & 1UL) != 0;")
                 .Close();
            }
            o.Line();

            o.Open($"public static Set Create({Sys}.ReadOnlySpan<{self}> items)")
             .Line($"ulong {Each(i => $"w{i} = 0")};");
            o.Open($"foreach ({self} item in items)");
            if (k == 1) o.Line("w0 |= 1UL << item._ordinal;");
            else
            {
                o.Line("int o = item._ordinal;")
                 .Line($"switch (o >> 6) {{ {Each(i => $"case {i}: w{i} |= 1UL << o; break;", " ")} }}");
            }
            o.Close()
             .Line($"return new({Each(i => $"w{i}")});")
             .Close().Line();

            o.Line($"public Set Add({self} item) => this | Of(item);")
             .Line($"public Set Remove({self} item) => this - Of(item);")
             .Line($"public int Count => {Each(i => $"{bo}.PopCount({w[i]})", " + ")};")
             .Line($"public bool IsEmpty => ({Each(i => w[i], " | ")}) == 0UL;")
             .Line("public bool IsSubsetOf(Set other) => (this - other).IsEmpty;")
             .Line("public bool IsSupersetOf(Set other) => (other - this).IsEmpty;")
             .Line("public bool Overlaps(Set other) => !(this & other).IsEmpty;")
             .Line();

            o.Line($"public static Set operator |(Set a, Set b) => new({Each(i => $"a.{w[i]} | b.{w[i]}")});")
             .Line($"public static Set operator &(Set a, Set b) => new({Each(i => $"a.{w[i]} & b.{w[i]}")});")
             .Line($"public static Set operator ^(Set a, Set b) => new({Each(i => $"a.{w[i]} ^ b.{w[i]}")});")
             .Line($"public static Set operator -(Set a, Set b) => new({Each(i => $"a.{w[i]} & ~b.{w[i]}")});")
             .Line($"public static Set operator ~(Set a) => new({Each(i => $"~a.{w[i]} & {masks[i]}")});")
             .Line($"public static implicit operator Set({self} item) => Of(item);")
             .Line();

            o.Line($"public bool Equals(Set other) => {Each(i => $"{w[i]} == other.{w[i]}", " && ")};")
             .Line("public override bool Equals(object? obj) => obj is Set other && Equals(other);")
             .Line($"public override int GetHashCode() => {(k == 1 ? "_w0.GetHashCode()" : $"{Sys}.HashCode.Combine({string.Join(", ", w.Take(8))})")};")
             .Line("public static bool operator ==(Set a, Set b) => a.Equals(b);")
             .Line("public static bool operator !=(Set a, Set b) => !a.Equals(b);")
             .Line();

            o.Line("/// <summary>Number of 64-bit words; bit i of word j is ordinal 64·j + i.</summary>")
             .Line($"public const int WordCount = {k};")
             .Line($"public ulong GetWord(int index) => index switch {{ {Each(i => $"{i} => {w[i]}")}, _ => throw new {Sys}.ArgumentOutOfRangeException(nameof(index)) }};")
             .Line("/// <summary>Missing words are zero; bits beyond <see cref=\"Count\"/> values are cleared.</summary>")
             .Line($"public static Set FromWords({Sys}.ReadOnlySpan<ulong> words) => new({Each(i => $"words.Length > {i} ? words[{i}] & {masks[i]} : 0UL")});")
             .Line();

            EmitSetIncludes(o, m, self, k, w);

            if (k == 1)
            {
                o.Line("/// <summary>Raw bits (bit i = ordinal i), e.g. for persistence.</summary>")
                 .Line("public ulong Bits => _w0;")
                 .Line($"public static Set FromBits(ulong bits) => new(bits & {masks[0]});")
                 .Line();
            }

            o.Open("public override string ToString()")
             .Line($"var sb = new {Sys}.Text.StringBuilder(\"[\");")
             .Line($"foreach ({self} item in this) {{ if (sb.Length > 1) sb.Append(\", \"); sb.Append(item.ToString()); }}")
             .Line("return sb.Append(']').ToString();")
             .Close().Line();

            // Allocation-free enumerator: peel the lowest set bit of each word.
            o.Line("public Enumerator GetEnumerator() => new(this);").Line();
            o.Open("public ref struct Enumerator")
             .Line($"private ulong {string.Join(", ", w)};")
             .Line("private int _current;")
             .Line($"internal Enumerator(Set set) {{ {Each(i => $"{w[i]} = set.{w[i]};", " ")} _current = -1; }}")
             .Line($"public {self} Current => new(({ord})_current);");
            o.Open("public bool MoveNext()");
            for (int i = 0; i < k; i++)
            {
                string add = i == 0 ? "" : $"{64 * i} + ";
                o.Line($"if ({w[i]} != 0UL) {{ _current = {add}{bo}.TrailingZeroCount({w[i]}); {w[i]} &= {w[i]} - 1UL; return true; }}");
            }
            o.Line("return false;")
             .Close()
             .Close()
             .Close();
        }

        /// <summary>
        /// Set conversions for each included block at bit offset <c>off</c>: widening shifts the
        /// included set's words left by <c>off</c>, narrowing shifts right and lets FromWords mask
        /// the last word. Offsets are constants, so every word is one or two shifts.
        /// </summary>
        private static void EmitSetIncludes(Writer o, EmitModel m, string self, int k, string[] w)
        {
            foreach (var inc in m.Includes)
            {
                string t = inc.FullName, s = inc.SimpleName;
                int kj = (inc.Count + 63) / 64;
                var parts = Enumerable.Range(0, k).Select(_ => new System.Collections.Generic.List<string>()).ToArray();
                for (int j = 0; j < kj; j++)
                {
                    int start = inc.Offset + 64 * j, w0 = start >> 6, r = start & 63;
                    parts[w0].Add(r == 0 ? $"s{j}" : $"(s{j} << {r})");
                    if (r != 0 && w0 + 1 < k) parts[w0 + 1].Add($"(s{j} >> {64 - r})");
                }

                o.Line($"public static implicit operator Set({t} value) => Of(({self})value);");
                o.Open($"public static implicit operator Set({t}.Set value)")
                 .Line($"ulong {string.Join(", ", Enumerable.Range(0, kj).Select(j => $"s{j} = value.GetWord({j})"))};")
                 .Line($"return new({string.Join(", ", parts.Select(p => p.Count == 0 ? "0UL" : string.Join(" | ", p)))});")
                 .Close();

                var words = Enumerable.Range(0, kj).Select(j =>
                {
                    int start = inc.Offset + 64 * j, w0 = start >> 6, r = start & 63;
                    if (r == 0) return w[w0];
                    return w0 + 1 < k ? $"({w[w0]} >> {r}) | ({w[w0 + 1]} << {64 - r})" : $"{w[w0]} >> {r}";
                });
                o.Line($"/// <summary>The <see cref=\"{inc.DisplayName}\"/> values in this set.</summary>")
                 .Line($"public {t}.Set To{s}Set() => {t}.Set.FromWords([{Join(words)}]);")
                 .Line();
            }
        }

        private static string Join(System.Collections.Generic.IEnumerable<string> items) => string.Join(", ", items);
        private static string Num(int i) => i.ToString(CultureInfo.InvariantCulture);
        private static string Quote(string s) => SymbolDisplay.FormatLiteral(s, quote: true);
    }
